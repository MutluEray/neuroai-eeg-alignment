"""Turn the CSVs into markdown tables you can paste into the README / website:   python3 make_report.py
Writes results/RESULTS.md from results/stats_*.csv, results/summary_main.csv and results/sensitivity.csv (if present)."""
import csv

import config


def read(p):
    return list(csv.DictReader(open(p))) if p.exists() else []


def f(x, nd=3, sign=False):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "n/a"
    return "n/a" if v != v else (f"{v:+.{nd}f}" if sign else f"{v:.{nd}f}")


def main():
    out = ["# Results (auto-generated by make_report.py)\n"]
    for w in config.WINDOWS:
        rows = read(config.RESULTS_DIR / f"stats_{w}.csv")
        if not rows:
            continue
        lo, hi = config.WINDOWS[w]
        out.append(f"\n## Paired comparisons, window '{w}' ({lo * 1000:.0f}-{hi * 1000:.0f} ms)\n")
        out.append("Normalized r at each model's leave-one-subject-out best layer. CIs are 95%: subjects / test images / both.\n")
        out.append("| comparison | A | B | A-B | CI subjects | CI images | CI both | p (Holm) |")
        out.append("|---|---|---|---|---|---|---|---|")
        for r in rows:
            out.append(f"| {r['comparison']} | {f(r['mean_a'])} | {f(r['mean_b'])} | {f(r['diff'], sign=True)} | "
                       f"[{f(r['ci_subj_lo'], sign=True)}, {f(r['ci_subj_hi'], sign=True)}] | "
                       f"[{f(r['ci_img_lo'], sign=True)}, {f(r['ci_img_hi'], sign=True)}] | "
                       f"[{f(r['ci_both_lo'], sign=True)}, {f(r['ci_both_hi'], sign=True)}] | {f(r['p_holm'], 4)} |")
    sens = read(config.RESULTS_DIR / "sensitivity.csv")
    if sens:
        out.append("\n## Sensitivity of ResNet-50 vs ViT-B/16 (grid readout)\n")
        out.append("| window | variant | ResNet-50 | ViT-grid | diff | 95% CI (subjects) |")
        out.append("|---|---|---|---|---|---|")
        for r in sens:
            out.append(f"| {r['window']} | {r['variant']} | {f(r['resnet50'])} | {f(r['vit_grid'])} | "
                       f"{f(r['diff'], sign=True)} | [{f(r['ci_lo'], sign=True)}, {f(r['ci_hi'], sign=True)}] |")
    summ = read(config.RESULTS_DIR / "summary_main.csv")
    if summ:
        out.append("\n## Best layer per model (picked on the group mean, so slightly optimistic)\n")
        out.append("| model | window | best layer | normalized r |")
        out.append("|---|---|---|---|")
        for m in config.MODELS:
            for w in config.WINDOWS:
                rs = [r for r in summ if r["model"] == m]
                if not rs:
                    continue
                b = max(rs, key=lambda r: float(r[f"norm_{w}_mean"]))
                out.append(f"| {m} | {w} | {b['layer']} | {f(b[f'norm_{w}_mean'])} |")
    p = config.RESULTS_DIR / "RESULTS.md"
    p.write_text("\n".join(out) + "\n")
    print("wrote", p)


if __name__ == "__main__":
    main()
